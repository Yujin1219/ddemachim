CREATE TABLE IF NOT EXISTS event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT,
    title VARCHAR(300) NOT NULL,
    event_type VARCHAR(30),
    start_date DATE,
    end_date DATE,
    source VARCHAR(30) NOT NULL,
    source_id VARCHAR(100) NOT NULL,
    venue_name VARCHAR(4000),
    org_name VARCHAR(200),
    use_target VARCHAR(4000),
    use_fee VARCHAR(4000),
    inquiry VARCHAR(4000),
    homepage_url VARCHAR(4000),
    main_image VARCHAR(4000),
    apply_date DATE,
    event_time VARCHAR(4000),
    event_start_time TIME,
    event_end_time TIME,
    detail_url VARCHAR(4000),
    location VARBINARY,
    CONSTRAINT uk_event_source UNIQUE (source, source_id)
);
